def fetch(name: str, weight: str) -> str:
    suffix = "" if weight == "regular" else f"-{weight}"
    url = f"{BASE}/{weight}/{name}{suffix}.svg"
    with urllib.request.urlopen(url) as r:
        return r.read().decode("utf-8")


def layers(svg: str, key: str) -> tuple[str, str]:
    if re.search(r"<(circle|rect|line|polyline|polygon|ellipse)\b", svg):
        sys.exit(f"{key}: path 이외의 도형이 있다")
    fill, outline = [], []
    for tag in re.findall(r"<path\b[^>]*>", svg):
        d = re.search(r'\bd="([^"]+)"', tag).group(1)
        (fill if 'opacity="0.2"' in tag else outline).append(d)
    return " ".join(fill), " ".join(outline)


def main() -> None:
    rows = []
    for key, (name, weight) in ICONS.items():
        fill, outline = layers(fetch(name, weight), key)
        if not outline:
            sys.exit(f"{key}: 윤곽이 비었다")
        rows.append(f'        ["{key}"] = ("{fill}", "{outline}"),')
    out = Path(__file__).resolve().parent.parent / "src/DaylightCommander.App/Icons/PhosphorIcons.g.cs"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(
        "// <auto-generated> scripts/gen-phosphor-icons.py 가 만든다. 직접 고치지 않는다.\n"
        f"// Phosphor Icons {VERSION} (MIT) https://phosphoricons.com\n"
        "namespace DaylightCommander.App.Icons;\n\n"
        "internal static partial class PhosphorIcons\n{\n"
        "    /// <summary>이름 → (채움 층, 윤곽 층). 둘 다 256×256 격자의 경로 데이터.</summary>\n"
        "    public static readonly Dictionary<string, (string Fill, string Outline)> Data = new()\n    {\n"
        + "\n".join(rows)
        + "\n    };\n}\n",
        encoding="utf-8",
    )
    print(f"{len(rows)}개 -> {out}")


main()
